#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const contractPath = resolve(repoRoot, "backend/src/main/resources/api-contract/frontend-api-contract.json");
const outputPath = resolve(repoRoot, "frontend/src/generated/api-types.ts");
const checkOnly = process.argv.includes("--check");

const contract = JSON.parse(readFileSync(contractPath, "utf8"));
const typeEntries = Object.entries(contract.types ?? {}).sort(([left], [right]) => left.localeCompare(right));

function tsName(contractName) {
  return contractName.replace(/[^A-Za-z0-9_$]/g, "");
}

function literal(value) {
  return JSON.stringify(value);
}

function typeOf(descriptor) {
  if (!descriptor || typeof descriptor !== "object") {
    return "unknown";
  }
  switch (descriptor.kind) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrapArrayItem(typeOf(descriptor.itemType))}[]`;
    case "map":
      return `Record<string, ${typeOf(descriptor.valueType)}>`;
    case "ref":
      return tsName(descriptor.name);
    case "unknown":
    default:
      return "unknown";
  }
}

function wrapArrayItem(value) {
  return value.includes(" | ") ? `(${value})` : value;
}

function enumType(name, descriptor) {
  const values = descriptor.values ?? [];
  const union = values.length === 0 ? "never" : values.map(literal).join(" | ");
  return `export type ${tsName(name)} = ${union};`;
}

function recordType(name, descriptor) {
  const fields = descriptor.fields ?? [];
  if (fields.length === 0) {
    return `export type ${tsName(name)} = Record<string, never>;`;
  }
  const body = fields.map((field) => {
    const optional = field.nullable ? "?" : "";
    const nullable = field.nullable ? " | null" : "";
    return `${JSON.stringify(field.name)}${optional}: ${typeOf(field.type)}${nullable};`;
  }).join(" ");
  return `export type ${tsName(name)} = { ${body} };`;
}

const enumValues = Object.fromEntries(
  typeEntries
    .filter(([, descriptor]) => descriptor.kind === "enum")
    .map(([name, descriptor]) => [name, descriptor.values ?? []])
);

const declarations = typeEntries.map(([name, descriptor]) => {
  if (descriptor.kind === "enum") {
    return enumType(name, descriptor);
  }
  if (descriptor.kind === "record") {
    return recordType(name, descriptor);
  }
  return `export type ${tsName(name)} = unknown;`;
});

const output = `// Generated by scripts/generate-frontend-types.mjs.
// Source: backend/src/main/resources/api-contract/frontend-api-contract.json.
// Do not edit by hand.

export const API_CONTRACT_TYPE_NAMES = ${JSON.stringify(typeEntries.map(([name]) => name))} as const;

export const API_CONTRACT_ENUM_VALUES = ${JSON.stringify(enumValues)} as const;

${declarations.join("\n\n")}
`;

if (checkOnly) {
  const currentOutput = readFileSync(outputPath, "utf8");
  if (currentOutput !== output) {
    console.error("Generated frontend API types are stale. Run `npm run generate:api-types` in frontend/.");
    process.exit(1);
  }
  process.exit(0);
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
